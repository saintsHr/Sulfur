#pragma once

#include <stdbool.h>
#include <stdint.h>

#include "sulfur/utils/span.h"

typedef uint16_t sf_log_error_code_num;

typedef enum {
    SF_LOG_SEVERITY_INFO,
    SF_LOG_SEVERITY_WARNING,
    SF_LOG_SEVERITY_ERROR,
    SF_LOG_SEVERITY_FATAL
} sf_log_severity;

typedef enum {
    SF_LOG_GENERAL_INSUFFICIENT_MEMORY = 0x0000,
    SF_LOG_GENERAL_INTERNAL_ERROR = 0x0001,

    SF_LOG_DRIVER_NO_INPUT_FILE = 0x1000,
    SF_LOG_DRIVER_NO_OUTPUT_FILE = 0x1001,
    SF_LOG_DRIVER_UNKNOWN_FLAG = 0x1002,
    SF_LOG_DRIVER_CANNOT_OPEN_FILE = 0x1003,
    SF_LOG_DRIVER_NO_MODULE_PATH = 0x1004,
    SF_LOG_DRIVER_NO_MODULE_FILE = 0x1005,

    SF_LOG_PREP_TOO_MANY_DEFINES = 0x2000,

    SF_LOG_LEXER_UNDEFINED_TOKEN = 0x3000,

    SF_LOG_PARSER_UNEXPECTED_TOKEN = 0x4000,
    SF_LOG_PARSER_REPEATED_QUALIFIER = 0x4001,
    SF_LOG_PARSER_INVALID_IMPORT = 0x4002,

    SF_LOG_SEMANTIC_REDECLARATION = 0x5000,
    SF_LOG_SEMANTIC_REDEFINITION = 0x5001,
    SF_LOG_SEMANTIC_UNDECLARED = 0x5002,
    SF_LOG_SEMANTIC_UNINITIALIZED = 0x5003,
    SF_LOG_SEMANTIC_TYPE_MISMATCH = 0x5004,
    SF_LOG_SEMANTIC_INVALID_EXPLICIT_CAST = 0x5005,
    SF_LOG_SEMANTIC_INVALID_IMPLICIT_CAST = 0x5006,
    SF_LOG_SEMANTIC_LITERAL_OVERFLOW = 0x5007,
    SF_LOG_SEMANTIC_DIVISION_BY_ZERO = 0x5008,
    SF_LOG_SEMANTIC_CONSTANT_EXPR = 0x5009,
    SF_LOG_SEMANTIC_RETURN_OUTSIDE_FUNCTION = 0x500a,
    SF_LOG_SEMANTIC_NO_VALUE_RETURN = 0x500b,
    SF_LOG_SEMANTIC_VOID_RETURN_VALUE = 0x500c,
    SF_LOG_SEMANTIC_MISSING_RETURN = 0x500d,
    SF_LOG_SEMANTIC_INVALID_TYPE = 0x500e,
    SF_LOG_SEMANTIC_NO_MAIN_FUNCTION = 0x500f,
    SF_LOG_SEMANTIC_INVALID_RETURN_TYPE = 0x5010,
    SF_LOG_SEMANTIC_INVALID_PARAMETERS = 0x5011,
    SF_LOG_SEMANTIC_INVALID_ASSIGN = 0x5012,
    SF_LOG_SEMANTIC_INVALID_QUALIFIER = 0x5013,
    SF_LOG_SEMANTIC_INVALID_DEFINITION = 0x5014,
    SF_LOG_SEMANTIC_CONFLICTING_DECLARATION = 0x5015,
    SF_LOG_SEMANTIC_UNUSED_EXPRESSION = 0x5016,
    SF_LOG_SEMANTIC_USELESS_CAST = 0x5017,
    SF_LOG_SEMANTIC_ARGUMENT_COUNT = 0x5018,
    SF_LOG_SEMANTIC_CYCLIC_IMPORT = 0x5019,
    SF_LOG_SEMANTIC_INVALID_NAMESPACE = 0x501A,
    SF_LOG_SEMANTIC_NAME_TOO_LONG = 0x501B,
    SF_LOG_SEMANTIC_INVALID_CALL = 0x501C,

    SF_LOG_MODULE_NOT_FOUND = 0x6000
} sf_log_error_code;

typedef struct {
    const char *title;
    const char *desc;
    const char *hint;
    const char *file;
    sf_log_error_code_num code;
    sf_span span;
    sf_log_severity sev;
} sf_log_info;

void sf_log_init(void);
void sf_log_shutdown(void);
void sf_log_set_source(const char *filename, const char *content);

bool sf_log_had_errors(void);

void sf_log(
    const char *title, const char *desc, const char *hint, const char *file,
    sf_log_error_code_num code, sf_span span, sf_log_severity sev, ...
);
